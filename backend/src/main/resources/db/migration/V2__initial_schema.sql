-- Stage 1 schema.
-- Tenant isolation is enforced here by composite foreign keys (x_id, company_id): a child row can
-- never point to a parent of another company.
-- There are no hard deletes: every FK is ON DELETE RESTRICT; deactivate with active = false.
-- Codes (company.code, employee.code) are stored upper-case and checked by regex.

CREATE TABLE company (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code       varchar(20)  NOT NULL,
    name       varchar(120) NOT NULL,
    time_zone  varchar(64)  NOT NULL DEFAULT 'America/Costa_Rica',
    active     boolean      NOT NULL DEFAULT true,
    CONSTRAINT uq_company_code UNIQUE (code),
    CONSTRAINT ck_company_code CHECK (code ~ '^[A-Z0-9-]{3,20}$'),
    CONSTRAINT ck_company_name CHECK (btrim(name) <> '')
);

CREATE TABLE branch (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id     bigint           NOT NULL,
    name           varchar(120)     NOT NULL,
    latitude       double precision NOT NULL,
    longitude      double precision NOT NULL,
    radius_meters  integer          NOT NULL DEFAULT 100,
    CONSTRAINT fk_branch_company FOREIGN KEY (company_id) REFERENCES company (id) ON DELETE RESTRICT,
    CONSTRAINT uq_branch_id_company UNIQUE (id, company_id),
    CONSTRAINT uq_branch_company_name UNIQUE (company_id, name),
    CONSTRAINT ck_branch_latitude CHECK (latitude BETWEEN -90 AND 90),
    CONSTRAINT ck_branch_longitude CHECK (longitude BETWEEN -180 AND 180),
    CONSTRAINT ck_branch_radius CHECK (radius_meters BETWEEN 10 AND 5000)
);

CREATE TABLE employee (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id       bigint       NOT NULL,
    -- NULL only for ADMIN (ck_employee_branch_role); the composite FK is not enforced when NULL.
    branch_id        bigint       NULL,
    code             varchar(20)  NOT NULL,
    name             varchar(120) NOT NULL,
    job_title        varchar(80)  NULL,
    pin_hash         varchar(100) NOT NULL,
    role             varchar(10)  NOT NULL,
    active           boolean      NOT NULL DEFAULT true,
    consent_at       timestamptz  NULL,
    failed_attempts  integer      NOT NULL DEFAULT 0,
    locked_until     timestamptz  NULL,
    token_version    integer      NOT NULL DEFAULT 0,
    CONSTRAINT fk_employee_company FOREIGN KEY (company_id) REFERENCES company (id) ON DELETE RESTRICT,
    CONSTRAINT fk_employee_branch_company FOREIGN KEY (branch_id, company_id)
        REFERENCES branch (id, company_id) ON DELETE RESTRICT,
    CONSTRAINT uq_employee_company_code UNIQUE (company_id, code),
    CONSTRAINT uq_employee_id_company UNIQUE (id, company_id),
    CONSTRAINT ck_employee_code CHECK (code ~ '^[A-Z0-9-]{1,20}$'),
    CONSTRAINT ck_employee_role CHECK (role IN ('EMPLOYEE', 'ADMIN')),
    CONSTRAINT ck_employee_failed_attempts CHECK (failed_attempts >= 0),
    CONSTRAINT ck_employee_branch_role CHECK (role = 'ADMIN' OR branch_id IS NOT NULL)
);
CREATE INDEX ix_employee_company_active ON employee (company_id, active);

CREATE TABLE work_schedule (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id     bigint  NOT NULL,
    employee_id    bigint  NOT NULL,
    day_of_week    integer NOT NULL,
    start_time     time    NOT NULL,
    end_time       time    NOT NULL,
    grace_minutes  integer NOT NULL DEFAULT 0,
    CONSTRAINT fk_work_schedule_employee_company FOREIGN KEY (employee_id, company_id)
        REFERENCES employee (id, company_id) ON DELETE RESTRICT,
    CONSTRAINT uq_work_schedule_employee_day UNIQUE (employee_id, day_of_week),
    CONSTRAINT ck_work_schedule_day CHECK (day_of_week BETWEEN 1 AND 7),
    CONSTRAINT ck_work_schedule_times CHECK (end_time <> start_time),
    CONSTRAINT ck_work_schedule_grace CHECK (grace_minutes BETWEEN 0 AND 240)
);

CREATE TABLE time_entry (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id      bigint           NOT NULL,
    employee_id     bigint           NOT NULL,
    branch_id       bigint           NOT NULL,
    type            varchar(10)      NOT NULL,
    server_time     timestamptz      NOT NULL DEFAULT now(),
    device_time     timestamptz      NULL,
    latitude        double precision NULL,
    longitude       double precision NULL,
    distance_meters integer          NULL,
    source          varchar(10)      NOT NULL,
    synced_late     boolean          NOT NULL DEFAULT false,
    -- varchar(20): the longest value, PENDING_REVIEW, has 14 characters.
    status          varchar(20)      NOT NULL DEFAULT 'VALID',
    client_uuid     uuid             NOT NULL,
    CONSTRAINT fk_time_entry_employee_company FOREIGN KEY (employee_id, company_id)
        REFERENCES employee (id, company_id) ON DELETE RESTRICT,
    CONSTRAINT fk_time_entry_branch_company FOREIGN KEY (branch_id, company_id)
        REFERENCES branch (id, company_id) ON DELETE RESTRICT,
    -- Offline idempotency key, unique per tenant.
    CONSTRAINT uq_time_entry_company_client_uuid UNIQUE (company_id, client_uuid),
    CONSTRAINT uq_time_entry_id_company UNIQUE (id, company_id),
    CONSTRAINT ck_time_entry_type CHECK (type IN ('CLOCK_IN', 'CLOCK_OUT')),
    CONSTRAINT ck_time_entry_source CHECK (source IN ('MOBILE', 'TABLET', 'QR')),
    CONSTRAINT ck_time_entry_status CHECK (status IN ('VALID', 'PENDING_REVIEW', 'REJECTED')),
    CONSTRAINT ck_time_entry_latitude CHECK (latitude BETWEEN -90 AND 90),
    CONSTRAINT ck_time_entry_longitude CHECK (longitude BETWEEN -180 AND 180),
    CONSTRAINT ck_time_entry_distance CHECK (distance_meters >= 0)
);
CREATE INDEX ix_time_entry_company_server_time ON time_entry (company_id, server_time);
CREATE INDEX ix_time_entry_employee_server_time ON time_entry (employee_id, server_time);
CREATE INDEX ix_time_entry_pending_review ON time_entry (company_id) WHERE status = 'PENDING_REVIEW';

CREATE TABLE evidence (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id    bigint       NOT NULL,
    time_entry_id bigint       NOT NULL,
    type          varchar(10)  NOT NULL,
    -- Storage key, not a public URL. NULL for GPS evidence (no file).
    storage_key   varchar(500) NULL,
    created_at    timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT fk_evidence_time_entry_company FOREIGN KEY (time_entry_id, company_id)
        REFERENCES time_entry (id, company_id) ON DELETE RESTRICT,
    CONSTRAINT ck_evidence_type CHECK (type IN ('PHOTO', 'GPS', 'QR'))
);
CREATE INDEX ix_evidence_time_entry ON evidence (time_entry_id);

CREATE TABLE adjustment (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id    bigint      NOT NULL,
    time_entry_id bigint      NOT NULL,
    -- The ADMIN role of admin_id is checked in the app (Stage 4).
    admin_id      bigint      NOT NULL,
    reason        text        NOT NULL,
    -- Audit row: which field changed, from what (NULL when the adjustment creates an entry) to what.
    field         text        NOT NULL,
    old_value     text        NULL,
    new_value     text        NOT NULL,
    created_at    timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT fk_adjustment_time_entry_company FOREIGN KEY (time_entry_id, company_id)
        REFERENCES time_entry (id, company_id) ON DELETE RESTRICT,
    CONSTRAINT fk_adjustment_admin_company FOREIGN KEY (admin_id, company_id)
        REFERENCES employee (id, company_id) ON DELETE RESTRICT,
    CONSTRAINT ck_adjustment_reason CHECK (btrim(reason) <> '')
);
CREATE INDEX ix_adjustment_time_entry ON adjustment (time_entry_id);
