-- Stage 1 schema.
-- Tenant isolation is enforced here by composite foreign keys (x_id, empresa_id): a child row can
-- never point to a parent of another empresa.
-- There are no hard deletes: every FK is ON DELETE RESTRICT; deactivate with activo = false.
-- Codes (empresa.codigo, empleado.codigo) are stored upper-case and checked by regex.

CREATE TABLE empresa (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo        varchar(20)  NOT NULL,
    nombre        varchar(120) NOT NULL,
    zona_horaria  varchar(64)  NOT NULL DEFAULT 'America/Costa_Rica',
    activo        boolean      NOT NULL DEFAULT true,
    CONSTRAINT uq_empresa_codigo UNIQUE (codigo),
    CONSTRAINT ck_empresa_codigo CHECK (codigo ~ '^[A-Z0-9-]{3,20}$'),
    CONSTRAINT ck_empresa_nombre CHECK (btrim(nombre) <> '')
);

CREATE TABLE sucursal (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id    bigint           NOT NULL,
    nombre        varchar(120)     NOT NULL,
    latitud       double precision NOT NULL,
    longitud      double precision NOT NULL,
    radio_metros  integer          NOT NULL DEFAULT 100,
    CONSTRAINT fk_sucursal_empresa FOREIGN KEY (empresa_id) REFERENCES empresa (id) ON DELETE RESTRICT,
    CONSTRAINT uq_sucursal_id_empresa UNIQUE (id, empresa_id),
    CONSTRAINT uq_sucursal_empresa_nombre UNIQUE (empresa_id, nombre),
    CONSTRAINT ck_sucursal_latitud CHECK (latitud BETWEEN -90 AND 90),
    CONSTRAINT ck_sucursal_longitud CHECK (longitud BETWEEN -180 AND 180),
    CONSTRAINT ck_sucursal_radio CHECK (radio_metros BETWEEN 10 AND 5000)
);

CREATE TABLE empleado (
    id                   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id           bigint       NOT NULL,
    -- NULL only for ADMIN (ck_empleado_sucursal_rol); the composite FK is not enforced when NULL.
    sucursal_id          bigint       NULL,
    codigo               varchar(20)  NOT NULL,
    nombre               varchar(120) NOT NULL,
    puesto               varchar(80)  NULL,
    pin_hash             varchar(100) NOT NULL,
    rol                  varchar(10)  NOT NULL,
    activo               boolean      NOT NULL DEFAULT true,
    consentimiento_fecha timestamptz  NULL,
    intentos_fallidos    integer      NOT NULL DEFAULT 0,
    bloqueado_hasta      timestamptz  NULL,
    token_version        integer      NOT NULL DEFAULT 0,
    CONSTRAINT fk_empleado_empresa FOREIGN KEY (empresa_id) REFERENCES empresa (id) ON DELETE RESTRICT,
    CONSTRAINT fk_empleado_sucursal_empresa FOREIGN KEY (sucursal_id, empresa_id)
        REFERENCES sucursal (id, empresa_id) ON DELETE RESTRICT,
    CONSTRAINT uq_empleado_empresa_codigo UNIQUE (empresa_id, codigo),
    CONSTRAINT uq_empleado_id_empresa UNIQUE (id, empresa_id),
    CONSTRAINT ck_empleado_codigo CHECK (codigo ~ '^[A-Z0-9-]{1,20}$'),
    CONSTRAINT ck_empleado_rol CHECK (rol IN ('EMPLEADO', 'ADMIN')),
    CONSTRAINT ck_empleado_intentos CHECK (intentos_fallidos >= 0),
    CONSTRAINT ck_empleado_sucursal_rol CHECK (rol = 'ADMIN' OR sucursal_id IS NOT NULL)
);
CREATE INDEX ix_empleado_empresa_activo ON empleado (empresa_id, activo);

CREATE TABLE horario (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id     bigint  NOT NULL,
    empleado_id    bigint  NOT NULL,
    dia_semana     integer NOT NULL,
    hora_entrada   time    NOT NULL,
    hora_salida    time    NOT NULL,
    tolerancia_min integer NOT NULL DEFAULT 0,
    CONSTRAINT fk_horario_empleado_empresa FOREIGN KEY (empleado_id, empresa_id)
        REFERENCES empleado (id, empresa_id) ON DELETE RESTRICT,
    CONSTRAINT uq_horario_empleado_dia UNIQUE (empleado_id, dia_semana),
    CONSTRAINT ck_horario_dia CHECK (dia_semana BETWEEN 1 AND 7),
    CONSTRAINT ck_horario_horas CHECK (hora_salida <> hora_entrada),
    CONSTRAINT ck_horario_tolerancia CHECK (tolerancia_min BETWEEN 0 AND 240)
);

CREATE TABLE marca (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id         bigint           NOT NULL,
    empleado_id        bigint           NOT NULL,
    sucursal_id        bigint           NOT NULL,
    tipo               varchar(10)      NOT NULL,
    hora_servidor      timestamptz      NOT NULL DEFAULT now(),
    hora_dispositivo   timestamptz      NULL,
    latitud            double precision NULL,
    longitud           double precision NULL,
    distancia_m        integer          NULL,
    origen             varchar(10)      NOT NULL,
    sincronizada_tarde boolean          NOT NULL DEFAULT false,
    estado             varchar(12)      NOT NULL DEFAULT 'VALIDA',
    client_uuid        uuid             NOT NULL,
    CONSTRAINT fk_marca_empleado_empresa FOREIGN KEY (empleado_id, empresa_id)
        REFERENCES empleado (id, empresa_id) ON DELETE RESTRICT,
    CONSTRAINT fk_marca_sucursal_empresa FOREIGN KEY (sucursal_id, empresa_id)
        REFERENCES sucursal (id, empresa_id) ON DELETE RESTRICT,
    -- Offline idempotency key, unique per tenant.
    CONSTRAINT uq_marca_empresa_client_uuid UNIQUE (empresa_id, client_uuid),
    CONSTRAINT uq_marca_id_empresa UNIQUE (id, empresa_id),
    CONSTRAINT ck_marca_tipo CHECK (tipo IN ('ENTRADA', 'SALIDA')),
    CONSTRAINT ck_marca_origen CHECK (origen IN ('MOVIL', 'TABLET', 'QR')),
    CONSTRAINT ck_marca_estado CHECK (estado IN ('VALIDA', 'POR_REVISAR', 'RECHAZADA')),
    CONSTRAINT ck_marca_latitud CHECK (latitud BETWEEN -90 AND 90),
    CONSTRAINT ck_marca_longitud CHECK (longitud BETWEEN -180 AND 180),
    CONSTRAINT ck_marca_distancia CHECK (distancia_m >= 0)
);
CREATE INDEX ix_marca_empresa_hora ON marca (empresa_id, hora_servidor);
CREATE INDEX ix_marca_empleado_hora ON marca (empleado_id, hora_servidor);
CREATE INDEX ix_marca_por_revisar ON marca (empresa_id) WHERE estado = 'POR_REVISAR';

CREATE TABLE evidencia (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id  bigint       NOT NULL,
    marca_id    bigint       NOT NULL,
    tipo        varchar(10)  NOT NULL,
    -- Storage key, not a public URL. NULL for GPS evidence (no file).
    url_archivo varchar(500) NULL,
    creada      timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT fk_evidencia_marca_empresa FOREIGN KEY (marca_id, empresa_id)
        REFERENCES marca (id, empresa_id) ON DELETE RESTRICT,
    CONSTRAINT ck_evidencia_tipo CHECK (tipo IN ('FOTO', 'GPS', 'QR'))
);
CREATE INDEX ix_evidencia_marca ON evidencia (marca_id);

CREATE TABLE ajuste (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id     bigint      NOT NULL,
    marca_id       bigint      NOT NULL,
    -- The ADMIN role of admin_id is checked in the app (Stage 4).
    admin_id       bigint      NOT NULL,
    motivo         text        NOT NULL,
    -- Audit row: which field changed, from what (NULL when the adjustment creates a mark) to what.
    campo          text        NOT NULL,
    valor_anterior text        NULL,
    valor_nuevo    text        NOT NULL,
    fecha          timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT fk_ajuste_marca_empresa FOREIGN KEY (marca_id, empresa_id)
        REFERENCES marca (id, empresa_id) ON DELETE RESTRICT,
    CONSTRAINT fk_ajuste_admin_empresa FOREIGN KEY (admin_id, empresa_id)
        REFERENCES empleado (id, empresa_id) ON DELETE RESTRICT,
    CONSTRAINT ck_ajuste_motivo CHECK (btrim(motivo) <> '')
);
CREATE INDEX ix_ajuste_marca ON ajuste (marca_id);
