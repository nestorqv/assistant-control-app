ALTER TABLE time_entry DROP CONSTRAINT ck_time_entry_source;
ALTER TABLE time_entry ADD CONSTRAINT ck_time_entry_source
    CHECK (source IN ('MOBILE', 'TABLET', 'QR', 'ADMIN'));

